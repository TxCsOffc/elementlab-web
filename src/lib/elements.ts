const num = (s: string) => (s === '-' ? undefined : Number(s));

export const ELEMENTS: Element[] = RAW.trim().split('\n').map((line) => {
  const f = line.split('|').map((x) => x.trim());
  return {z: Number(f[0]), symbol: f[1], name: t(f[2]), mass: Number(f[3]), category: CAT[f[4]] ?? 'unknown',
    melt: num(f[5]), boil: num(f[6]), density: num(f[7]), en: num(f[8]), radius: num(f[9]), abundance: num(f[10])};
});

export const byZ = new Map(ELEMENTS.map((e) => [e.z, e]));
export const element = (z: number) => byZ.get(z);

export function period(z: number) {
  if (z <= 2) return 1; if (z <= 10) return 2; if (z <= 18) return 3; if (z <= 36) return 4;
  if (z <= 54) return 5; if (z <= 86) return 6; return 7;
}
export const isFBlock = (z: number) => (z >= 57 && z <= 71) || (z >= 89 && z <= 103);

export function group(z: number): number | undefined {
  if (isFBlock(z)) return undefined;
  const p = period(z);
  if (p === 1) return z === 1 ? 1 : 18;
  if (p === 2 || p === 3) { const off = z - (p === 2 ? 3 : 11); return off < 2 ? off + 1 : off + 11; }
  if (p === 4 || p === 5) return z - (p === 4 ? 19 : 37) + 1;
  const start = p === 6 ? 55 : 87; const off = z - start;
  if (off < 2) return off + 1;
  return z - (p === 6 ? 72 : 104) + 4;
}

/** Позиция в сетке: колонка 1..18, строка 0..8.4 (f-блок ниже) */
export function gridPos(z: number): [number, number] {
  if (isFBlock(z)) return [3 + (z - (z <= 71 ? 57 : 89)), (z <= 71 ? 7 : 8) + 0.4];
  return [group(z) ?? 1, period(z) - 1];
}

export const atomDiameterNm = (e: Element) => (e.radius ? (2 * e.radius) / 1000 : undefined);
